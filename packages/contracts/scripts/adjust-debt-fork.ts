import {readFile} from "node:fs/promises";
import {network} from "hardhat";
import {AAVE_POOL_ABI,AAVE_DEBT_ABI,verifyAaveBase} from "./lib/aave-base.ts";
const {ethers}=await network.create();
const metadata=await ethers.provider.send("hardhat_metadata",[]);
if(metadata.forkedNetwork?.forkBlockNumber!==51123118)throw Error("Debt fixture adjustment requires the controlled local Base fork");
const runtime=JSON.parse(await readFile("../frontend/.runtime/firmdepth.json","utf8"));
await verifyAaveBase(ethers.provider,runtime.addresses.usdc);
const [,,borrower]=await ethers.getSigners();
const config=runtime.debtRepayment;
const pool=new ethers.Contract(config.pool,AAVE_POOL_ABI,borrower);
const debt=new ethers.Contract(config.variableDebtToken,AAVE_DEBT_ABI,ethers.provider);
const usdc=new ethers.Contract(runtime.addresses.usdc,["function approve(address,uint256) returns(bool)"],borrower);
const current=await debt.balanceOf(await borrower.getAddress());
const target=100_000_000n;
if(current<=target)throw Error("Fixture already has debt below the target");
const amount=current-target;
await (await usdc.approve(config.pool,amount)).wait();
const receipt=await (await pool.repay(runtime.addresses.usdc,amount,2,await borrower.getAddress())).wait();
if(receipt.status!==1)throw Error("Real Aave fixture repayment failed");
console.log("Debt reduced through actual Aave Pool.repay:",receipt.hash,"remaining:",(await debt.balanceOf(await borrower.getAddress())).toString());
