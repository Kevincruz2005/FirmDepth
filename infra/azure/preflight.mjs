import {readFile} from 'node:fs/promises';
import {createRequire} from 'node:module';
import {fileURLToPath} from 'node:url';
const require=createRequire(new URL('../../packages/quote-service/package.json',import.meta.url));
const {createPublicClient,http,getAddress}=require('viem');
const {privateKeyToAccount}=require('viem/accounts');
const {authenticateFirmDepthDeployment}=await import('../../packages/sdk/dist/deployment.js');
const {authenticateSettlement}=await import('../../packages/sdk/dist/settlement.js');
const required=['AZURE_SUBSCRIPTION_ID','AZURE_RESOURCE_GROUP','AZURE_LOCATION','AZURE_PLAN','AZURE_APP_NAME','AZURE_KEY_VAULT','MAKER_PRIVATE_KEY','SEPOLIA_RPC_URL','PUBLIC_BROWSER_RPC_URL','PUBLIC_API_URL','FIRMDEPTH_SETTLEMENT_ADDRESS'];
const missing=required.filter(name=>!process.env[name]?.trim());
if(missing.length)throw Error(`Missing settings: ${missing.join(', ')}`);
const manifest=JSON.parse(await readFile(new URL('../../deployments/sepolia.json',import.meta.url),'utf8'));
const key=process.env.MAKER_PRIVATE_KEY;
if(!/^0x[0-9a-fA-F]{64}$/.test(key))throw Error('MAKER_PRIVATE_KEY must be a 32-byte key');
if(getAddress(privateKeyToAccount(key).address)!==getAddress(manifest.maker))throw Error('Maker signer does not match the existing Sepolia manifest');
const client=createPublicClient({transport:http(process.env.SEPOLIA_RPC_URL,{timeout:15000})});
if(await client.getChainId()!==11155111)throw Error('Private RPC must use Sepolia');
await authenticateFirmDepthDeployment(client,manifest.addresses);
await authenticateSettlement(client,getAddress(process.env.FIRMDEPTH_SETTLEMENT_ADDRESS),manifest.addresses);
const publicClient=createPublicClient({transport:http(process.env.PUBLIC_BROWSER_RPC_URL,{timeout:15000})});
if(await publicClient.getChainId()!==11155111)throw Error('Browser RPC must use Sepolia');
if(new URL(process.env.PUBLIC_API_URL).protocol!=='https:')throw Error('Azure API URL must use HTTPS');
const origins=(process.env.CORS_ORIGINS??'http://127.0.0.1:4173').split(',');
for(const origin of origins)if(origin==='*'||new URL(origin).origin!==origin)throw Error('CORS must contain exact origins');
console.log('Azure deployment preflight passed: signer, Sepolia contracts, protected settlement, public RPC and origins verified.');
